def make_gold() -> list[dict]:
    """Create 60 grounded cases with alternative evidence chunks per fact."""
    corpus = Corpus.load()
    groups = defaultdict(list)
    for row in corpus.chunks:
        groups[row["source_id"]].append(row)
    sources = list(groups)
    rows = []

    def add(doc, question, answer, facts=(), category="fact", forbidden=()):
        """Add one authored case with source-verified facts and alternative evidence."""
        source = sources[doc]
        split = "dev" if doc in {0, 2, 4, 6, 10} else "test"
        annotated = []
        for i, item in enumerate(facts):
            # Explicit needle proves provenance; aliases are independently written answer patterns.
            needle, patterns = item[0], item[1:]
            relevant = [r for r in groups[source] if needle in r["text"]]
            assert relevant, (source, needle)
            chunk = relevant[0]
            pos = chunk["text"].index(needle)
            quote = chunk["text"][
                max(0, pos - 100) : min(len(chunk["text"]), pos + len(needle) + 120)
            ]
            annotated.append(
                {
                    "id": f"fact-{i + 1}",
                    "patterns": list(patterns) or [re.escape(needle)],
                    "needle": needle,
                    "evidence_ids": [r["chunk_id"] for r in relevant],
                    "quote": quote,
                    "primary_chunk_id": chunk["chunk_id"],
                }
            )
        rows.append(
            {
                "id": f"{split}-{sum(r['split'] == split for r in rows) + 1:02d}",
                "split": split,
                "group_id": source,
                "source_ids": [source],
                "category": category,
                "question": question,
                "expected_status": "ok" if annotated else "not_found",
                "reference_answer": answer,
                "required_facts": annotated,
                "forbidden_patterns": list(forbidden),
                "annotation_provenance": "author_reviewed",
            }
        )

