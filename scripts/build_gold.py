def main():
    """Write committed, inspectable annotations and a frozen split manifest."""
    rows = make_gold()
    folder = ROOT / "data/gold"
    folder.mkdir(parents=True, exist_ok=True)
    for split in ["dev", "test"]:
        selected = [r for r in rows if r["split"] == split]
        (folder / f"{split}.jsonl").write_text(
            "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in selected)
        )
    manifest = {
        "version": "gold-1.0",
        "sha256": digest(rows),
        "dev": 20,
        "test": 40,
        "split_unit": "source transcript; all paraphrases and nearby facts stay together",
        "created_at": "2026-10-20",
        "annotation_provenance": "author_reviewed",
    }
    (folder / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2)
    )
    print(json.dumps(manifest, ensure_ascii=False))


if __name__ == "__main__":
    main()
