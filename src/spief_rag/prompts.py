def answer_system(config: Experiment) -> str:
    """Compose the exact instruction and explicitly synthetic few-shot examples."""
    text = CORE + ("" if config.short_prompt else LONG)
    if config.examples:
        text += (
            "\nУчебные примеры формата. Это НЕ источники ответа на текущий вопрос:\n"
        )
        text += json.dumps(EXAMPLES[: config.examples], ensure_ascii=False)
    return text


